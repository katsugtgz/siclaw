"""Regenerate source_kinds.json from Siclaw kbc's source classification.

Usage: python3 generate.py <siclaw-checkout> > source_kinds.json

The registry lists and every case's expected value come from the real
kbc/platform/pod/source_kinds.py, so the Go port is checked against the
compiler's own answers rather than against a hand-written expectation.
"""

import json
import subprocess
import sys
from pathlib import Path

CASES = [
    # Ordinary and hidden files at the Raw root.
    "index.md", ".mintignore", ".DS_Store", ".env", ".gitignore",
    ".GITIGNORE", ".gitlab-ci.yml", ".env.example", ".gitkeep",
    # Hidden files below ordinary directories.
    "docs/.mintignore", "docs/.gitignore", "docs/guide/.DS_Store",
    # Hidden directories: allowlisted, case-folded, and arbitrary.
    ".github/workflows/ci.yml", ".GitHub/workflows/ci.yml",
    ".gitlab/issue_templates/bug.md", ".devcontainer/devcontainer.json",
    ".circleci/config.yml", ".cache/page.md", "docs/.vitepress/config.ts",
    ".git/config", ".github/.cache/x.json", ".github/.gitkeep",
    ".github/.gitignore",
    # Windows separators normalize like the compiler's replace("\\", "/").
    "docs\\.mintignore", ".github\\workflows\\ci.yml",
    # Text classification.
    "guide.mdx", "guide.MDX", "api.rst", "page.html", "page.htm",
    "feed.xml", "table.tsv", "events.jsonl", "notes.txt", "data.csv",
    "config.json", "config.yaml", "config.yml", "main.go", "app.tsx",
    "go.sum", "Cargo.lock", "Dockerfile", "dockerfile.agentbox",
    "Makefile", "Makefile.release", "makefile-old", "Dockerfiles",
    "LICENSE", "notice", "README", "logo.png", "slides.pptx", "report.pdf",
    "archive.tar.gz", "photo.JPG", "diagram.svg",
]


def main() -> None:
    checkout = Path(sys.argv[1]).resolve()
    sys.path.insert(0, str(checkout / "kbc" / "platform" / "pod"))
    import source_kinds as sk

    head = subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "--short=8", "HEAD"],
        check=True, capture_output=True, text=True,
    ).stdout.strip()
    out = {
        "_comment": "Generated by generate.py from Siclaw "
                    "kbc/platform/pod/source_kinds.py; do not edit by hand.",
        "siclaw_commit": head,
        "document_text_exts": sorted(sk.DOCUMENT_TEXT_EXTS),
        "code_text_exts": sorted(sk.CODE_TEXT_EXTS),
        "text_source_basenames": sorted(sk.TEXT_SOURCE_BASENAMES),
        "text_source_prefixes": list(sk.TEXT_SOURCE_PREFIXES),
        "visible_hidden_source_dirs": sorted(sk.VISIBLE_HIDDEN_SOURCE_DIRS),
        "visible_hidden_source_files": sorted(sk.VISIBLE_HIDDEN_SOURCE_FILES),
        "cases": [
            {
                "path": p,
                "managed": sk.is_managed_source_path(p),
                "text": sk.is_text_source_path(p),
            }
            for p in CASES
        ],
    }
    json.dump(out, sys.stdout, ensure_ascii=False, indent=2)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
